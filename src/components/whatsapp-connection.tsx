"use client";
import { useEffect, useState } from "react";
import { ChannelHealthButton } from "@/components/channel-health-button";

type Connection = { status: string; address?: string | null; qr?: string | null; error?: string };
const labels: Record<string, string> = { disconnected: "Not connected", connecting: "Connecting…", qr: "Scan to connect", connected: "Connected", reconnecting: "Reconnecting…", reconnect_required: "Reconnect required", error: "Connection failed", unavailable: "Unavailable" };
export function WhatsAppConnection() {
  const [connection, setConnection] = useState<Connection>({ status: "disconnected" });
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  useEffect(() => {
    let active = true;
    let timer: ReturnType<typeof setTimeout>;
    const controller = new AbortController();
    async function poll() {
      try {
        const response = await fetch("/api/channels/whatsapp", { cache: "no-store", signal: controller.signal });
        const data = await response.json();
        if (active && response.ok) { setConnection(data); setError(""); }
        else if (active) { setConnection({ status: "unavailable" }); setError(data.error || "Unable to check WhatsApp"); }
      } catch { if (active) setError("Unable to check WhatsApp"); }
      if (active) timer = setTimeout(poll, 3000);
    }
    void poll();
    return () => { active = false; controller.abort(); clearTimeout(timer); };
  }, []);
  async function act(method: "POST" | "DELETE") {
    setBusy(true); setError("");
    try {
      const response = await fetch("/api/channels/whatsapp", { method });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || "Unable to update WhatsApp");
      setConnection(data);
    } catch (error) { setError(error instanceof Error ? error.message : "Unable to update WhatsApp"); }
    finally { setBusy(false); }
  }
  const active = ["connecting", "qr", "connected", "reconnecting"].includes(connection.status);
  return <div>
    <p role="status" className="mb-3 text-sm">{labels[connection.status] || "Not connected"}{connection.address ? ` · +${connection.address}` : ""}</p>
    <div className="flex flex-wrap items-start gap-3"><button type="button" disabled={busy || connection.status === "unavailable"} onClick={() => void act(active ? "DELETE" : "POST")} className="inline-flex min-h-12 items-center justify-center rounded-md border border-[var(--border)] px-4 py-2 text-sm font-medium hover:border-[var(--accent)] disabled:opacity-50">{busy ? "Updating…" : active ? "Disconnect WhatsApp" : "Connect WhatsApp"}</button><ChannelHealthButton provider="whatsapp" /></div>
    {connection.qr && <div className="mt-4"><p className="mb-3 text-sm text-[var(--muted)]">Open WhatsApp on your phone → Settings → Linked Devices → Link a Device.</p>{/* QR is generated by our service, never an external URL. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={connection.qr} alt="Scan this QR code in WhatsApp to link your account" width={256} height={256} className="rounded-lg" /></div>}
    {error && <p role="alert" className="mt-3 text-sm text-[var(--status-red)]">{error}</p>}
  </div>;
}
